function defaultDockShortcuts(): ShortcutItem[] {
  return DEFAULT_DOCK_ROUTES.split(",")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((route) => ({
      kind: "route",
      target: route,
      action: "",
      label: "",
      icon: "",
      confirm: false,
    }));
}

export function buildDevicePrefsForRecord(rec: MockDeviceRecord): DevicePrefItem[] {
  if (rec.entry.kind === "ble_tag") return [];
  const out: DevicePrefItem[] = [];
  for (const spec of DEVICE_PREF_SPECS_CATALOG) {
    if (!isCatalogItemSupported(spec, rec.capabilities)) continue;
    const val = spec.key in rec.config ? rec.config[spec.key] : spec.default;
    out.push({
      key: spec.key,
      label: spec.label,
      section: spec.section,
      group_tier: spec.group_tier,
      domain: spec.domain,
      value: val,
      options: spec.options ? [...spec.options] : undefined,
      min: spec.min ?? undefined,
      max: spec.max ?? undefined,
      step: spec.step ?? undefined,
      unit: spec.unit || undefined,
    });
  }
  return out;
}

